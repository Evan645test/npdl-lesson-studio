// 教師手冊用的空白班級彙整表（每個測次、每個子指標各一份）。
export const CLASS_TABLE_HEADER = '門檻｜通過＿＿｜邊界＿＿｜未通過＿＿｜尚無法判讀＿＿｜分母（本次提供的學生）＿＿';
export function judgmentLines(modes: readonly SetMode[] = ['B']): string[] {
  const used = [...new Set(modes)];
  return [
    ...used.flatMap(mode => MODE_RULES[mode]),
    ...(used.some(mode => mode !== 'E') ? [...DATA_RULES] : []),
    ...(used.includes('B') ? [
      ...THRESHOLD_RULES,
      '精熟判讀表（第 5 題｜非選題第三段｜判讀）：',
      ...MASTERY_ROWS.map(row => `・${row.join('｜')}`),
      MASTERY_FEATURE,
      INCONSISTENT_RULES[0],
    ] : []),
    ...(used.some(mode => mode === 'B' || mode === 'C' || mode === 'D') ? INCONSISTENT_RULES.slice(1) : used.includes('A') ? [INCONSISTENT_RULES[1], INCONSISTENT_RULES[3]] : []),
    ...(used.some(mode => mode !== 'E') ? [...CLASS_RULES.slice(1)] : []),
    ...(used.some(mode => mode === 'B' || mode === 'C' || mode === 'D') ? [CLASS_RULES[0]] : []),
    ...(used.includes('B') || used.includes('C') ? [ADMINISTRATION_NOTE] : []),
  ];
}
